//! Lesson 05-3: `impl Trait`
//!
//! 引数位置（呼び出し側が具体的な型を選ぶ）と戻り値位置（実装側が1つの
//! 具体的な型に決める）の両方を実装する。

/// 引数位置の impl Trait: Display を実装した値なら何でも受け取れる。
pub fn shout(x: impl std::fmt::Display) -> String {
    todo!("xを文字列化し、大文字にして返してください（to_uppercase）")
}

/// 戻り値位置の impl Trait: 呼び出し側には具体的な型を教えないが、
/// 実装の中では1つの型（`Filter<Range<i32>, _>`）に決まっている。
///
/// 注意: `impl Trait` の戻り値は、コンパイラが「本体のどこかにある具体的な式」から
/// 型を決める。関数全体をそのまま `todo!()` にすると、型を決める手がかりが無くなり
/// コンパイルできない。骨組みは外側の式（`(0..n).filter(...)`）を残し、
/// 中の条件式だけを埋めるようにしてある。
pub fn evens_up_to(n: i32) -> impl Iterator<Item = i32> {
    (0..n).filter(|x| todo!("x が偶数かどうかを返してください（x % 2 == 0）"))
}
